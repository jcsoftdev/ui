// Generates one Kotlin file per icon (and alias) from packages/ui/icons, the same SVG source the web icons use.
// Usage: node build-icons.mjs <icons-dir> <out-dir>
// Writes <out-dir>/main (kit sources) and <out-dir>/test (a name list used only by tests).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PACKAGE = "com.jcsoftdev.ui.icons";

export function pascalCase(kebab) {
  return kebab
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

const num = (value) => {
  const n = Number(value);
  if (Number.isNaN(n)) throw new Error(`not a number: ${value}`);
  return String(Math.round(n * 1e4) / 1e4);
};

/** Child elements of the <svg> as `{tag, attrs}` in document order. */
export function parseSvg(source) {
  const inner = source.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const nodes = [];
  for (const match of inner.matchAll(/<(\w+)\s+([^>]*?)\s*\/>/g)) {
    const attrs = Object.fromEntries([...match[2].matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
    nodes.push({ tag: match[1], attrs });
  }
  return nodes;
}

const arc = (rx, ry, dx, dy) => `a${num(rx)} ${num(ry)} 0 1 0 ${num(dx)} ${num(dy)}`;

/** Path data for one shape element. Only the Lucide subset is supported; anything else throws. */
export function toPathData({ tag, attrs }) {
  const a = (name, fallback) => Number(attrs[name] ?? fallback);
  switch (tag) {
    case "path":
      return attrs.d;
    case "circle": {
      const [cx, cy, r] = [a("cx", 0), a("cy", 0), a("r")];
      return `M${num(cx - r)} ${num(cy)}${arc(r, r, 2 * r, 0)}${arc(r, r, -2 * r, 0)}`;
    }
    case "ellipse": {
      const [cx, cy, rx, ry] = [a("cx", 0), a("cy", 0), a("rx"), a("ry")];
      return `M${num(cx - rx)} ${num(cy)}${arc(rx, ry, 2 * rx, 0)}${arc(rx, ry, -2 * rx, 0)}`;
    }
    case "rect": {
      const [x, y, w, h] = [a("x", 0), a("y", 0), a("width"), a("height")];
      let rx = attrs.rx !== undefined ? a("rx") : a("ry", 0);
      let ry = attrs.ry !== undefined ? a("ry") : rx;
      rx = Math.min(rx, w / 2);
      ry = Math.min(ry, h / 2);
      if (rx === 0 || ry === 0) return `M${num(x)} ${num(y)}h${num(w)}v${num(h)}h${num(-w)}z`;
      const corner = (dx, dy) => `a${num(rx)} ${num(ry)} 0 0 1 ${num(dx)} ${num(dy)}`;
      return (
        `M${num(x + rx)} ${num(y)}h${num(w - 2 * rx)}${corner(rx, ry)}v${num(h - 2 * ry)}` +
        `${corner(-rx, ry)}h${num(-(w - 2 * rx))}${corner(-rx, -ry)}v${num(-(h - 2 * ry))}${corner(rx, -ry)}z`
      );
    }
    case "line":
      return `M${num(a("x1", 0))} ${num(a("y1", 0))}L${num(a("x2", 0))} ${num(a("y2", 0))}`;
    case "polyline":
    case "polygon": {
      const pts = attrs.points.trim().split(/[\s,]+/).map(Number);
      const pairs = [];
      for (let i = 0; i < pts.length; i += 2) pairs.push(`${num(pts[i])} ${num(pts[i + 1])}`);
      return `M${pairs[0]}${pairs.slice(1).map((p) => `L${p}`).join("")}${tag === "polygon" ? "z" : ""}`;
    }
    default:
      throw new Error(`unsupported SVG element <${tag}>`);
  }
}

const HEADER = `// Generated by packages/ui-compose/scripts/build-icons.mjs. Do not edit.
// Icon shapes from Lucide (https://lucide.dev), ISC License, Copyright (c) 2026 Lucide Icons and Contributors.
// Full notice: packages/ui/icons/LICENSE-lucide.`;

const lower = (name) => name[0].toLowerCase() + name.slice(1);

export function renderIcon(name, source, file) {
  const paths = parseSvg(source).map((node) => JSON.stringify(toPathData(node)));
  const field = `_${lower(name)}`;
  return `${HEADER}
// Source: packages/ui/icons/svg/${file}.svg
package ${PACKAGE}

import androidx.compose.ui.graphics.vector.ImageVector

private var ${field}: ImageVector? = null

public val Icons.${name}: ImageVector
    get() = ${field} ?: lucideIcon("${name}", ${paths.join(", ")}).also { ${field} = it }
`;
}

export function renderAlias(alias, canonical) {
  return `${HEADER}
// Alias of ${canonical}
package ${PACKAGE}

import androidx.compose.ui.graphics.vector.ImageVector

public val Icons.${alias}: ImageVector
    get() = Icons.${canonical}
`;
}

export function generate({ svgDir, aliasFile }) {
  const files = new Map();
  const files_ = fs
    .readdirSync(svgDir)
    .filter((f) => f.endsWith(".svg"))
    .map((f) => f.slice(0, -4))
    .sort();
  const names = [];
  for (const file of files_) {
    const name = pascalCase(file);
    files.set(`${name}.kt`, renderIcon(name, fs.readFileSync(path.join(svgDir, `${file}.svg`), "utf8"), file));
    names.push(name);
  }
  const aliasNames = [];
  const aliases = JSON.parse(fs.readFileSync(aliasFile, "utf8"));
  for (const [alias, canonical] of Object.entries(aliases)) {
    if (!names.includes(canonical)) throw new Error(`alias ${alias} points to unknown icon ${canonical}`);
    files.set(`${alias}.kt`, renderAlias(alias, canonical));
    aliasNames.push(alias);
  }
  const all = [...names, ...aliasNames].sort();
  const list = `${HEADER}
package ${PACKAGE}

import androidx.compose.ui.graphics.vector.ImageVector

internal val GeneratedIconNames: List<String> = listOf(
${all.map((n) => `    "${n}",`).join("\n")}
)

internal val GeneratedIcons: List<Pair<String, () -> ImageVector>> = listOf(
${all.map((n) => `    "${n}" to { Icons.${n} },`).join("\n")}
)

internal const val GeneratedSvgCount: Int = ${names.length}

internal const val GeneratedAliasCount: Int = ${aliasNames.length}
`;
  return { main: files, test: new Map([["GeneratedIcons.kt", list]]) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [iconsDir, outDir] = process.argv.slice(2);
  if (!iconsDir || !outDir) throw new Error("usage: build-icons.mjs <icons-dir> <out-dir>");
  const { main, test } = generate({
    svgDir: path.join(iconsDir, "svg"),
    aliasFile: path.join(iconsDir, "aliases.json"),
  });
  const pkgPath = PACKAGE.split(".").join("/");
  for (const [dir, files] of [["main", main], ["test", test]]) {
    const target = path.join(outDir, dir, pkgPath);
    fs.rmSync(path.join(outDir, dir), { recursive: true, force: true });
    fs.mkdirSync(target, { recursive: true });
    for (const [file, content] of files) fs.writeFileSync(path.join(target, file), content);
  }
  console.log(`generated ${main.size} icons in ${outDir}`);
}
