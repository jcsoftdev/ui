// Compiles the per-component CSS for vanilla users: every `src/**/*.css` becomes a string module
// (`*.css.ts`, adopted into shadow roots or into the root node of light-DOM composites), and with
// `--dist` a plain `dist/css/<name>.css`. The Liquid Glass material is generated from the
// `@utility liquid` / `@utility liquid-clear` blocks of @jcsoftdev/ui-tokens (the same rules the
// React kit's Tailwind utilities apply), retargeted to `[data-ui-liquid]`.
// Every `var(--x)` must be a token from ui-tokens' tokens.css, a component variable (`--ui-*`) or a
// runtime variable of the liquid engine; anything else fails the build.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { basename, dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "src");
const dist = process.argv.includes("--dist");
const require = createRequire(join(root, "package.json"));
const tokensDir = dirname(require.resolve("@jcsoftdev/ui-tokens/styles/tokens.css"));
const tokensCss = readFileSync(join(tokensDir, "tokens.css"), "utf8");
const themeCss = readFileSync(join(tokensDir, "theme.css"), "utf8");
const tokens = new Set([...tokensCss.matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1]));
/** Variables the liquid engine and the option mapping write at run time. */
const RUNTIME = /^--(ui-|liquid-|glass-)/;

const minify = (css) =>
  css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{};])\s*/g, "$1")
    .replace(/,\s+/g, ",")
    .replace(/;}/g, "}")
    .trim();

function check(css, file, allowRuntime) {
  const bad = [...css.matchAll(/var\(\s*(--[\w-]+)/g)]
    .map((m) => m[1])
    .filter((name) => !tokens.has(name) && !(allowRuntime ? RUNTIME : /^--ui-/).test(name));
  if (bad.length) throw new Error(`${file}: unknown variables ${[...new Set(bad)].join(", ")}`);
}

/** Body of `@utility <name> { ... }` from theme.css, braces balanced. */
function utility(name) {
  const start = themeCss.indexOf(`@utility ${name} {`);
  if (start < 0) throw new Error(`ui-tokens theme.css has no @utility ${name}`);
  let depth = 0;
  for (let i = themeCss.indexOf("{", start); i < themeCss.length; i++) {
    if (themeCss[i] === "{") depth++;
    else if (themeCss[i] === "}" && --depth === 0)
      return themeCss.slice(themeCss.indexOf("{", start) + 1, i);
  }
  throw new Error(`unbalanced @utility ${name}`);
}

function liquidCss() {
  const retarget = (body) =>
    body
      .replaceAll(".liquid, .liquid-clear,", ".liquid, .liquid-clear, [data-ui-liquid],")
      .replaceAll(":not(:disabled)", ":not(:disabled, [disabled])");
  return minify(
    `[data-ui-liquid]:not([data-ui-liquid="clear"]){${retarget(utility("liquid"))}}` +
      `[data-ui-liquid="clear"]{${retarget(utility("liquid-clear"))}}`,
  );
}

function* cssFiles(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* cssFiles(path);
    else if (entry.name.endsWith(".css")) yield path;
  }
}

const outputs = [];
for (const file of cssFiles(src)) {
  const css = minify(readFileSync(file, "utf8"));
  check(css, relative(root, file), false);
  outputs.push([file, css]);
}
const liquid = liquidCss();
check(liquid, "liquid material", true);
outputs.push([join(src, "internal/liquid.css"), liquid]);

for (const [file, css] of outputs) {
  writeFileSync(
    `${file}.ts`,
    `// Generated by scripts/build-css.mjs. Do not edit.\nexport default ${JSON.stringify(css)};\n`,
  );
  if (dist) {
    mkdirSync(join(root, "dist/css"), { recursive: true });
    writeFileSync(join(root, "dist/css", basename(file)), `${css}\n`);
  }
}
console.log(`build-css: ${outputs.length} stylesheets${dist ? " (+ dist/css)" : ""}`);
