/** The children of the `<svg>` as compact markup, in document order. */
export function body(source) {
  const inner = source.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const nodes = [...inner.matchAll(/<(\w+)\s+([^>]*?)\s*\/>/g)].map(
    ([, tag, attrs]) =>
      `<${tag} ${[...attrs.matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => `${m[1]}="${m[2]}"`).join(" ")}/>`,
  );
  const leftover = inner.replace(/<(\w+)\s+([^>]*?)\s*\/>/g, "").trim();
  if (leftover) throw new Error(`unsupported markup: ${leftover}`);
  return nodes.join("");
}

/** @returns {Map<string, string>} glyph id to svg children. */
export function glyphs() {
  const svgDir = join(iconsDir, "svg");
  const map = new Map();
  for (const file of readdirSync(svgDir).filter((f) => f.endsWith(".svg")))
    map.set(file.slice(0, -4), body(readFileSync(join(svgDir, file), "utf8")));
  // Lucide renames the React kit keeps as aliases (`AlertTriangle` -> `TriangleAlert`).
  const pascal = (kebab) =>
    kebab
      .split("-")
      .map((part) => part[0].toUpperCase() + part.slice(1))
      .join("");
  const aliases = JSON.parse(readFileSync(join(iconsDir, "aliases.json"), "utf8"));
  for (const [alias, canonical] of Object.entries(aliases)) {
    const target = [...map.keys()].find((id) => pascal(id) === canonical);
    if (!target) throw new Error(`alias ${alias} points to unknown icon ${canonical}`);
    map.set(alias.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase(), map.get(target));
  }
  const base = new Map(map);
  for (const [short, id] of Object.entries(SHORTHANDS)) {
    const target = base.get(id);
    if (!target) throw new Error(`shorthand ${short} points to unknown icon ${id}`);
    // `file` is the React shorthand for file-text; the plain file glyph stays reachable.
    if (map.has(short) && map.get(short) !== target) map.set(`${short}-plain`, map.get(short));
    map.set(short, target);
  }
  return map;
}

const renderRegistry = (ids) =>
  `${HEADER}
// One lazy loader per glyph: the bundler splits each into its own chunk, so rendering one icon
// fetches this map and that glyph only. The map itself is behind import() in icon.ts.
export const registry = {
${ids.map((id) => `  ${JSON.stringify(id)}: () => import("./glyphs/${id}.js"),`).join("\n")}
} as const;

export type IconName = keyof typeof registry;
`;

const render = (markup) => `${HEADER}\nexport default ${JSON.stringify(markup)};\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const all = glyphs();
  if (process.argv.includes("--check")) {
    const stale = [...all].filter(
      ([id, markup]) =>
        !existsSync(join(outDir, `${id}.ts`)) ||
        !readFileSync(join(outDir, `${id}.ts`), "utf8").includes(markup),
    );
    const extra = existsSync(outDir)
      ? readdirSync(outDir).filter((f) => !all.has(f.replace(/\.ts$/, "")))
      : [];
    const listed = existsSync(registryFile)
      ? [...readFileSync(registryFile, "utf8").matchAll(/glyphs\/(.+?)\.js"/g)].map((m) => m[1])
      : [];
    if (listed.length !== all.size || listed.some((id) => !all.has(id))) stale.push(["registry"]);
    if (stale.length || extra.length) {
      console.error(`icon glyphs are stale (${stale.length} changed, ${extra.length} extra)`);
      process.exit(1);
    }
    console.log(`${all.size} glyph modules in sync`);
  } else {
    rmSync(outDir, { recursive: true, force: true });
    mkdirSync(outDir, { recursive: true });
    for (const [id, markup] of all) writeFileSync(join(outDir, `${id}.ts`), render(markup));
    writeFileSync(registryFile, renderRegistry([...all.keys()].sort()));
    console.log(`generated ${all.size} glyph modules in src/icon/glyphs`);
  }
}
