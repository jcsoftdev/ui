// Generates one lazy glyph module per icon id into src/icon/glyphs/, from the React kit's SVG
// sources (packages/ui/icons). A module is `export default "<svg children>"`; <ui-icon> imports it
// on demand, so a page pays only for the glyphs it renders.
//   node scripts/build-icons.mjs          write src/icon/glyphs
//   node scripts/build-icons.mjs --check  fail when the committed glyphs are stale
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const iconsDir = join(root, "../ui/icons");
const outDir = join(root, "src/icon/glyphs");
const registryFile = join(root, "src/icon/registry.ts");
const HEADER = "// Generated by scripts/build-icons.mjs. Do not edit.";

