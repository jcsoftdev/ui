/** One group per side/axis: `("p", "p", ["", "x"], v)` gives `p` and `px`; `joiner` sits before the side. */
function perSide(
  id: string,
  prefix: string,
  sides: string[],
  values: Def[],
  joiner = "",
): GroupEntry[] {
  return sides.map((s) => [
    s ? `${id}${joiner}${s}` : id,
    s ? `${prefix}${joiner}${s}` : prefix,
    values,
  ]);
}

/** `mask-image-*` from/to stops: a position group then a color group per edge. */
function maskStops(edges: string[]): GroupEntry[] {
  const out: GroupEntry[] = [];
  for (const edge of edges) {
    for (const end of ["from", "to"]) {
      out.push([`mask-image-${edge}-${end}-pos`, `mask-${edge}-${end}`, maskImagePosition]);
    }
    for (const end of ["from", "to"]) {
      out.push([`mask-image-${edge}-${end}-color`, `mask-${edge}-${end}`, colorScale]);
    }
  }
  return out;
}

