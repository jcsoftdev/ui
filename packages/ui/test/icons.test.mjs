import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { generate, parseSvg, pascalCase } from "../scripts/build-icons.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const svgDir = path.join(root, "icons/svg");
const aliasFile = path.join(root, "icons/aliases.json");

test("renders a known icon from its SVG source", () => {
  const files = generate({ svgDir, aliasFile });
  const check = files.get("check.tsx");
  assert.match(check, /^\/\/ Generated by scripts\/build-icons\.mjs/);
  assert.match(check, /export function Check\(props: IconProps\)/);
  assert.match(check, /<path d="M20 6 9 17l-5-5" \/>/);
});

test("maps aliases to their canonical icon", () => {
  const files = generate({ svgDir, aliasFile });
  assert.match(
    files.get("alert-triangle.tsx"),
    /export \{ TriangleAlert as AlertTriangle \} from "\.\/triangle-alert\.js";/,
  );
  assert.match(files.get("index.ts"), /export \{ AlertTriangle \} from/);
});

test("every SVG becomes a component with exactly the source paths", () => {
  const files = generate({ svgDir, aliasFile });
  const svgs = fs.readdirSync(svgDir).filter((f) => f.endsWith(".svg"));
  assert.ok(svgs.length >= 130);
  for (const svg of svgs) {
    const file = svg.slice(0, -4);
    const source = fs.readFileSync(path.join(svgDir, svg), "utf8");
    const out = files.get(`${file}.tsx`);
    assert.ok(out, `${file} generated`);
    assert.match(out, new RegExp(`export function ${pascalCase(file)}\\(`));
    for (const [, attrs] of parseSvg(source)) {
      for (const [key, value] of attrs)
        assert.ok(out.includes(`${key}="${value}"`), `${file}: ${key}`);
    }
    assert.equal(
      (out.match(/\/>/g) ?? []).length,
      parseSvg(source).length,
      `${file}: element count`,
    );
  }
});

test("committed src/icons matches the generator output", () => {
  const files = generate({ svgDir, aliasFile });
  for (const [file, content] of files) {
    assert.equal(
      fs.readFileSync(path.join(root, "src/icons", file), "utf8"),
      content,
      `${file} is stale, run node scripts/build-icons.mjs`,
    );
  }
});

test("barber-only names are available", () => {
  const index = fs.readFileSync(path.join(root, "src/icons/index.ts"), "utf8");
  for (const name of [
    "Armchair",
    "Construction",
    "Tags",
    "UserPlus",
    "ShoppingBag",
    "ShoppingCart",
    "ArrowUpFromLine",
  ]) {
    assert.match(index, new RegExp(`export \\{ ${name} \\}`));
  }
});
