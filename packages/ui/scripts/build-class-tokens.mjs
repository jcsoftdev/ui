// Derives the class-merge token lists from styles/theme.css into src/utils/class-tokens.generated.ts.
// Usage: node scripts/build-class-tokens.mjs [--check]   (--check fails when the file is stale)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const THEME = path.join(root, "styles/theme.css");
const OUT = path.join(root, "src/utils/class-tokens.generated.ts");

/** Theme namespace -> exported constant and doc line. */
const NAMESPACES = [
  ["text", "TEXT_SIZES", "`text-*` font-size tokens; without them they would read as colors."],
  ["radius", "RADII", "`rounded-*` radius tokens (role radii and legacy names)."],
  ["shadow", "SHADOWS", "`shadow-*` tokens (role shadows and legacy names)."],
  [
    "spacing",
    "SPACINGS",
    "Spacing tokens used by `h-*`, `w-*`, `p-*`, `gap-*`, `inset-*` and friends.",
  ],
];

/** Names declared as `--<namespace>-<name>:`, in file order, without `--modifier` sub-properties. */
export function tokensOf(css, namespace) {
  const seen = new Set();
  for (const m of css.matchAll(new RegExp(`^\\s*--${namespace}-([a-z0-9-]+):`, "gm"))) {
    if (!m[1].includes("--")) seen.add(m[1]);
  }
  return [...seen];
}

export function render(css) {
  const blocks = NAMESPACES.map(([ns, name, doc]) => {
    const items = tokensOf(css, ns)
      .map((t) => `  "${t}",\n`)
      .join("");
    return `/** ${doc} */\nexport const ${name}: readonly string[] = [\n${items}];\n`;
  });
  return `// Generated by scripts/build-class-tokens.mjs from styles/theme.css. Do not edit.\n\n${blocks.join("\n")}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render(fs.readFileSync(THEME, "utf8"));
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== out) {
      console.error("class-tokens.generated.ts is stale: run `pnpm build:class-tokens`");
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUT, out);
    console.log(`wrote ${path.relative(root, OUT)}`);
  }
}
