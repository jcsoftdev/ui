// Builds src/charts/maps/data/{peru,world}.ts from Natural Earth GeoJSON (public domain).
//
//   node scripts/build-map-data.mjs <dir with the two .geojson files>
//
// Expects, inside <dir>:
//   ne_10m_admin_1_states_provinces.geojson   (Peru departments)
//   ne_110m_admin_0_countries.geojson         (world)
// Source and license: src/charts/maps/data/README.md
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const input = resolve(process.argv[2] ?? "");
if (!process.argv[2]) throw new Error("usage: build-map-data.mjs <dir with the geojson files>");

const bundle = await build({
  entryPoints: [join(root, "src/charts/maps/geo/build-topology.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  write: false,
});
const { buildTopology } = await import(
  `data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].contents).toString("base64")}`
);

const read = (name) => JSON.parse(readFileSync(join(input, name), "utf8"));
const geometryOf = (feature) => feature.geometry;

function write(file, header, map) {
  const source = `// Generated by scripts/build-map-data.mjs from Natural Earth (public domain). Do not edit.
// ${header}
import type { GeoMap } from "../../geo/types.js";

export const ${map.name}: GeoMap = ${JSON.stringify(map.value)};
`;
  writeFileSync(join(root, "src/charts/maps/data", file), source);
  console.log(
    file,
    `${(Buffer.byteLength(source) / 1024).toFixed(1)} KB`,
    `${map.value.topology.arcs.length} arcs`,
  );
}

// Peru: 24 departments + Callao, with Lima split into the region and the metropolitan province.
const admin1 = read("ne_10m_admin_1_states_provinces.geojson");
const peru = admin1.features
  .filter((feature) => feature.properties.adm0_a3 === "PER")
  .map((feature) => {
    const metropolitan = feature.properties.name === "Lima Province";
    return {
      id: metropolitan ? "PE-LMA" : feature.properties.iso_3166_2,
      name: metropolitan
        ? "Lima Metropolitana"
        : feature.properties.name === "Lima"
          ? "Lima (región)"
          : feature.properties.name,
      geometry: geometryOf(feature),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name, "es"));
write("peru/index.ts", "Peru by department (admin-1), simplified.", {
  name: "peruMap",
  value: {
    id: "pe-departamentos",
    name: "Perú",
    projection: "fitted",
    object: "departamentos",
    topology: buildTopology(peru, {
      object: "departamentos",
      quantization: 20_000,
      tolerance: 0.004,
      minArea: 0.0004,
    }),
  },
});

// World: countries at 1:110m, without Antarctica (it stretches Mercator to infinity).
const admin0 = read("ne_110m_admin_0_countries.geojson");
const world = admin0.features
  .filter((feature) => feature.properties.ADM0_A3 !== "ATA")
  .map((feature) => ({
    id:
      feature.properties.ISO_A3_EH && feature.properties.ISO_A3_EH !== "-99"
        ? feature.properties.ISO_A3_EH
        : feature.properties.ADM0_A3,
    name: feature.properties.NAME_ES ?? feature.properties.NAME,
    geometry: geometryOf(feature),
  }))
  .sort((a, b) => a.name.localeCompare(b.name, "es"));
write("world/index.ts", "World countries, 1:110m, simplified.", {
  name: "worldMap",
  value: {
    id: "world-paises",
    name: "Mundo",
    projection: "equalEarth",
    object: "paises",
    topology: buildTopology(world, {
      object: "paises",
      quantization: 20_000,
      tolerance: 0.06,
      minArea: 0.1,
    }),
  },
});
