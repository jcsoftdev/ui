// Generates one React component per SVG in icons/svg into src/icons/, plus the barrel.
// Usage: node scripts/build-icons.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function pascalCase(kebab) {
  return kebab
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

/** Child elements of the <svg> as `[tag, attrs]` pairs, in document order. */
export function parseSvg(source) {
  const inner = source.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const nodes = [];
  for (const match of inner.matchAll(/<(\w+)\s+([^>]*?)\s*\/>/g)) {
    const attrs = [...match[2].matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]);
    nodes.push([match[1], attrs]);
  }
  return nodes;
}

const HEADER = "// Generated by scripts/build-icons.mjs. Do not edit.";

export function renderIcon(name, source, file) {
  const nodes = parseSvg(source)
    .map(([tag, attrs]) => `      <${tag} ${attrs.map(([k, v]) => `${k}="${v}"`).join(" ")} />`)
    .join("\n");
  return `${HEADER}
// Source: icons/svg/${file}.svg
import { IconBase, type IconProps } from "./icon-base.js";

export function ${name}(props: IconProps) {
  return (
    <IconBase {...props}>
${nodes}
    </IconBase>
  );
}
`;
}

export function generate({ svgDir, aliasFile }) {
  const files = new Map();
  const names = fs
    .readdirSync(svgDir)
    .filter((f) => f.endsWith(".svg"))
    .map((f) => f.slice(0, -4))
    .sort();
  const exportsList = [];
  for (const file of names) {
    const name = pascalCase(file);
    files.set(
      `${file}.tsx`,
      renderIcon(name, fs.readFileSync(path.join(svgDir, `${file}.svg`), "utf8"), file),
    );
    exportsList.push([name, file]);
  }
  const aliases = JSON.parse(fs.readFileSync(aliasFile, "utf8"));
  for (const [alias, canonical] of Object.entries(aliases)) {
    const target = names.find((f) => pascalCase(f) === canonical);
    if (!target) throw new Error(`alias ${alias} points to unknown icon ${canonical}`);
    const file = alias.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
    files.set(
      `${file}.tsx`,
      `${HEADER}\n// Alias of ${canonical}\nexport { ${canonical} as ${alias} } from "./${target}.js";\n`,
    );
    exportsList.push([alias, file]);
  }
  exportsList.sort(([a], [b]) => a.localeCompare(b));
  const barrel = `${HEADER}\nexport { type IconComponent, type IconProps, type LucideIcon } from "./icon-base.js";\n${exportsList
    .map(([name, file]) => `export { ${name} } from "./${file}.js";`)
    .join("\n")}\n`;
  files.set("index.ts", barrel);
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outDir = path.join(root, "src/icons");
  const files = generate({
    svgDir: path.join(root, "icons/svg"),
    aliasFile: path.join(root, "icons/aliases.json"),
  });
  for (const f of fs.readdirSync(outDir)) {
    if (f === "icon-base.tsx" || f.endsWith(".test.mjs")) continue;
    fs.rmSync(path.join(outDir, f));
  }
  for (const [file, content] of files) fs.writeFileSync(path.join(outDir, file), content);
  console.log(`generated ${files.size - 1} icons in src/icons`);
}
